const assert = require('node:assert/strict'), { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.IMAGE_TEST_BROWSER || undefined });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } }); await context.setOffline(true);
    const page = await context.newPage(); await page.goto(pathToFileURL(require('./support/viewer-path.cjs')()).href);
    await page.waitForFunction(() => document.getElementById('codecStatus').dataset.state === 'ready', null, { timeout: 90000 });
    await page.locator('#sampleImage').click(); await page.waitForFunction(() => app.variants.slice(0,2).every(v => v.blob && !v.processing && !v.dirty), null, { timeout: 90000 });
    const cell = page.locator('.cell').nth(1), quality = cell.locator('.quality-wrap:has(input.quality)'), number = quality.locator('.range-number');
    assert.equal(await number.getAttribute('max'), '100');
    const before = await page.evaluate(() => app.variants[1].generation);
    await number.fill('3'); assert.equal(await page.evaluate(() => app.variants[1].config.quality), 85);
    await number.fill('30'); await number.press('Enter');
    assert.equal(await page.evaluate(() => app.variants[1].config.quality), 30);
    assert.equal(await page.evaluate(() => app.variants[1].generation), before + 1);
    await number.press('Tab'); assert.equal(await page.evaluate(() => app.variants[1].generation), before + 1);
    await number.fill('101'); await number.press('Enter'); assert.equal(await number.getAttribute('aria-invalid'), 'true');
    assert.equal(await page.evaluate(() => app.variants[1].config.quality), 30);
    await number.press('Escape'); assert.equal(await number.inputValue(), '30');
    const format = cell.locator('select').first();
    await format.selectOption('webpLossless');
    const effort = cell.locator('.modern-effort-wrap .range-number');
    assert.equal(await effort.getAttribute('min'), '0'); assert.equal(await effort.getAttribute('max'), '6');
    await effort.fill('6'); await effort.press('Tab'); assert.equal(await page.evaluate(() => app.variants[1].config.webpMethod), 6);
    await format.selectOption('jxl'); assert.equal(await effort.getAttribute('min'), '1'); assert.equal(await effort.getAttribute('max'), '10');
    await effort.fill('7'); await effort.press('Enter'); assert.equal(await page.evaluate(() => app.variants[1].config.jxlEffort), 7);
    await format.selectOption('avif'); const speed = cell.locator('.avif-speed-wrap .range-number');
    await speed.fill('8'); await speed.press('Enter'); assert.equal(await page.evaluate(() => app.variants[1].config.avifSpeed), 8);
    await page.locator('#analysisLevelField .range-number').fill('64'); await page.locator('#analysisLevelField .range-number').press('Enter');
    assert.equal(await page.locator('#analysisLevel').inputValue(), '64');
    await page.locator('#analysisType').selectOption('profile');
    const position = page.locator('#analysisPositionField .range-number'); await position.fill('12.3'); await position.press('Enter');
    assert.equal(await page.locator('#analysisPosition').inputValue(), '123');
    await page.locator('#displayMenuToggle').click(); await page.locator('#displayMode').selectOption('sdr');
    const exposure = page.locator('#displayMenu .range-number').nth(2); await exposure.fill('-1.25'); await exposure.press('Enter');
    assert.equal(await page.evaluate(() => app.display.exposure), -1.25);
    await page.locator('#displayMenuToggle').click();
    await page.locator('#convertAll').click(); await page.locator('#batchFormat').selectOption('avif');
    const batchSpeed = page.locator('#batchAvifSpeedField .range-number'); await batchSpeed.fill('4'); await batchSpeed.press('Enter');
    assert.equal(await page.locator('#batchAvifSpeed').inputValue(), '4');
    assert.equal(await page.locator('#batchDialog').evaluate(el => el.open), true, 'Enter must not submit the dialog');
    await page.locator('#batchDialogCancel').click();
    await page.setViewportSize({ width: 390, height: 844 });
    await format.selectOption('jpeg'); await number.fill('85'); await number.press('Enter');
    assert.equal(await page.evaluate(() => app.variants[1].config.quality), 85);
    assert.ok(await number.evaluate(el => { const r = el.getBoundingClientRect(), head = el.closest('.cell-head').getBoundingClientRect(); return r.width >= 50 && r.right <= head.right + 1; }));
    await page.reload(); await page.waitForFunction(() => app.variants?.[1]?.controls?.quality);
    assert.equal(await number.inputValue(), '85');
    assert.equal(await cell.locator('.avif-speed-wrap .range-number').inputValue(), '8');
    console.log('PASS numeric controls commit once, reject invalid drafts, track codec ranges, analysis, display, batch, narrow layout and restored settings');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
