const assert = require('node:assert/strict');
const {buildSync} = require('../scripts/node_modules/esbuild');
(async () => {
  const bundle=buildSync({entryPoints:['src/application.mjs'],bundle:true,write:false,format:'cjs',platform:'node',external:['viewer:*']}).outputFiles[0].text;
  const module={exports:{}};
  new Function('exports','module','require',bundle)(module.exports,module,name=>{assert(name.startsWith('viewer:'));return '';});
  const el={style:{},closest:()=>el,querySelector:()=>el,querySelectorAll:()=>[],getContext:()=>null};
  global.document={getElementById:()=>el,createElement:()=>el};
  const {app,actions}=module.exports.createApplication();
  app.variants=[];
  for(const name of ['clearBatchPreview','clearDisplayCache','syncDisplayControls','setEmptyState','drawAll','resetView','showStatus','updateAnalysis','updateStudySummary'])actions[name]=()=>{};
  const seen=[];
  actions.updateFormatOptions=()=>seen.push(app.source?.cmyk?'CMYK':'no CMYK');
  actions.decodeSourceFile=async file=>({name:file.name,width:1,height:1,...(file.name.endsWith('.tif')?{cmyk:{data:new Uint8Array(4)}}:{})});
  assert(await actions.loadFile({name:'first.tif'},{announce:false,renderPreview:false}));
  assert.deepEqual(seen,['no CMYK','CMYK'],'initial JPEG/TIFF controls must refresh after CMYK decode');
  seen.length=0;
  assert(await actions.loadFile({name:'next.png'},{announce:false,renderPreview:false}));
  assert.deepEqual(seen,['no CMYK','no CMYK']);
  seen.length=0;
  assert(await actions.loadFile({name:'again.tif'},{announce:false,renderPreview:false}));
  assert.deepEqual(seen,['no CMYK','CMYK']);
  seen.length=0;actions.disposeSource();
  assert.deepEqual(seen,['no CMYK']);
  actions.decodeSourceFile=async()=>{throw Error('bad input')};
  seen.length=0;
  assert.equal(await actions.loadFile({name:'bad.tif'},{announce:false,renderPreview:false}),false);
  assert(seen.length>=2&&seen.every(x=>x==='no CMYK'));
  assert.equal(app.source,null);
  console.log('PASS composition root refreshes format controls on first CMYK load, replacement, clear and failure');
})().catch(e=>{console.error(e);process.exitCode=1});
